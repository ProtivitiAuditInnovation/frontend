// Zero-dependency web server for the UAR frontend.
//   Local:  npm run dev        Azure App Service (Node, Linux or Windows):  npm start / web.config
// Settings come from frontend/.env or Azure App Settings (App Settings win). See .env.example.
const http = require("http");
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;

// ---- .env loader (KEY=VALUE lines; existing environment variables win)
function loadEnv(file) {
  if (!fs.existsSync(file)) return;
  for (const raw of fs.readFileSync(file, "utf8").replace(/^﻿/, "").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const i = line.indexOf("=");
    const key = line.slice(0, i).trim();
    const val = line.slice(i + 1).trim().replace(/^["']|["']$/g, "");
    if (!(key in process.env)) process.env[key] = val;
  }
}
loadEnv(path.join(ROOT, ".env"));

const ON_AZURE = !!process.env.WEBSITE_SITE_NAME;
// Azure (Linux) gives a port number; Azure (Windows, iisnode) gives a named pipe - pass either through unchanged
const RAW_PORT = process.env.PORT || "5500";
const PORT = /^\d+$/.test(RAW_PORT) ? Number(RAW_PORT) : RAW_PORT;
const HOST = process.env.HOST || (ON_AZURE ? "0.0.0.0" : "127.0.0.1");
// `npm run dev` (--local) talks to the backend on this machine; `npm start` (Azure) uses UAR_API_BASE
const LOCAL = process.argv.includes("--local");
const API_BASE = ((LOCAL ? process.env.UAR_API_BASE_LOCAL : process.env.UAR_API_BASE)
                  || "http://localhost:8000/api").replace(/\/+$/, "");

// Only these file types are served; dotfiles (.env), server code and config are never served.
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8", ".png": "image/png", ".svg": "image/svg+xml", ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg", ".ico": "image/x-icon", ".webp": "image/webp" };
const BLOCKED = new Set(["server.js", "package.json", "package-lock.json", "web.config"]);
const SECURITY_HEADERS = { "X-Content-Type-Options": "nosniff", "Referrer-Policy": "same-origin",
  "X-Frame-Options": "SAMEORIGIN" };

const configJs = () =>
  "// Generated by server.js from UAR_API_BASE (frontend/.env or App Settings).\n" +
  `window.UAR_CONFIG = { API_BASE: ${JSON.stringify(API_BASE)} };\n`;

function send(res, code, body, type) {
  res.writeHead(code, { "Content-Type": type || "text/plain; charset=utf-8", "Cache-Control": "no-store",
                        ...SECURITY_HEADERS });
  res.end(body);
}

const server = http.createServer((req, res) => {
  if (req.method !== "GET" && req.method !== "HEAD") return send(res, 405, "Method not allowed");
  let rel;
  try { rel = decodeURIComponent(req.url.split("?")[0]); } catch (e) { return send(res, 400, "Bad request"); }
  if (rel === "/" || rel === "") rel = "/index.html";
  if (rel === "/config.js") return send(res, 200, configJs(), TYPES[".js"]);
  if (rel === "/healthz") return send(res, 200, "ok");
  const file = path.normalize(path.join(ROOT, rel));
  const parts = path.relative(ROOT, file).split(path.sep);
  if (file !== ROOT && !file.startsWith(ROOT + path.sep)) return send(res, 403, "Forbidden");
  if (parts.some((p) => p.startsWith(".")) || BLOCKED.has(parts[parts.length - 1])
      || !TYPES[path.extname(file).toLowerCase()]) return send(res, 404, "Not found");
  fs.readFile(file, (err, data) => {
    if (err) return send(res, 404, "Not found");
    send(res, 200, data, TYPES[path.extname(file).toLowerCase()]);
  });
});

const onListen = () => {
  console.log(`UAR frontend listening on ${typeof PORT === "number" ? `http://${HOST}:${PORT}` : PORT}`);
  console.log(`Backend API: ${API_BASE}`);
};
if (typeof PORT === "number") server.listen(PORT, HOST, onListen);
else server.listen(PORT, onListen);
